// Isolated browser verification. Build first; never points at the production DB.
import { chromium, expect } from "@playwright/test";
import { spawn, execFileSync } from "node:child_process";
import { mkdtempSync, cpSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { randomBytes, scryptSync } from "node:crypto";

const root = process.cwd();
const directory = mkdtempSync(path.join(tmpdir(), "blog-dashboard-"));
const release = path.join(directory, "release");
cpSync(path.join(root, ".next/standalone"), release, { recursive: true });
cpSync(path.join(root, ".next/static"), path.join(release, ".next/static"), { recursive: true });
cpSync(path.join(root, "public"), path.join(release, "public"), { recursive: true });
const db = path.join(directory, "test.sqlite");
execFileSync(path.join(root, "node_modules/.bin/tsx"), ["scripts/import-mdx.ts"], { cwd: root, env: { ...process.env, BLOG_DB_PATH: db } });
const password = randomBytes(18).toString("hex");
const salt = randomBytes(16);
const origin = "http://127.0.0.1:3182";
const server = spawn(process.execPath, ["server.js"], { cwd: release, env: { ...process.env, HOSTNAME: "127.0.0.1", PORT: "3182", BLOG_DB_PATH: db, BLOG_TAILSCALE_IP: "127.0.0.1:3182", BLOG_SESSION_SECRET: randomBytes(32).toString("hex"), BLOG_ADMIN_PASSWORD_HASH: `scrypt:${salt.toString("hex")}:${scryptSync(password, salt, 64).toString("hex")}` }, stdio: "ignore" });
let browser;
const results = [];
const check = (name) => { results.push(name); console.log(`PASS ${name}`); };
try {
  for (let i = 0; i < 50; i++) { try { if ((await fetch(`${origin}/health/ready`)).ok) break; } catch {} await new Promise((resolve) => setTimeout(resolve, 200)); }
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`${origin}/admin`);
  await page.getByLabel("관리자 비밀번호", { exact: true }).fill(password);
  await page.getByRole("button", { name: "로그인", exact: true }).click();
  await expect(page.getByRole("heading", { name: "대시보드", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: /블로그 기반을/ })).toBeVisible();
  check("login and dashboard with migrated posts");
  await page.screenshot({ path: "/tmp/blog-admin-dashboard.png", fullPage: true });
  await page.getByRole("button", { name: "+ 새 글 작성", exact: true }).click();
  await page.getByLabel("제목", { exact: true }).fill("브라우저 통합 검증");
  await page.getByLabel("주소(slug)", { exact: false }).fill("dashboard-browser-check");
  await page.getByLabel("설명", { exact: true }).fill("별도 테스트 데이터베이스의 글");
  await page.getByLabel("MDX 본문", { exact: true }).fill('# 통합 미리보기\n\n<Callout title="확인">안전한 컴포넌트</Callout>');
  await expect(page.getByRole("heading", { name: "통합 미리보기" })).toBeVisible();
  page.once("dialog", (dialog) => dialog.dismiss());
  await page.getByRole("button", { name: "글 관리", exact: true }).click();
  await expect(page.getByRole("heading", { name: "새 글 작성" })).toBeVisible();
  check("split preview and unsaved navigation warning");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByText(/저장했습니다 ·/)).toBeVisible();
  expect((await page.request.get(`${origin}/life/posts/dashboard-browser-check`)).status()).toBe(404);
  check("draft is not public");
  await page.getByLabel("발행 상태").selectOption("published");
  const saved = page.waitForResponse((response) => response.request().method() === "PUT" && response.url().includes("dashboard-browser-check"));
  await page.getByRole("button", { name: "저장", exact: true }).click();
  expect((await saved).status()).toBe(200);
  expect((await page.request.get(`${origin}/life/posts/dashboard-browser-check`)).status()).toBe(200);
  check("publish immediately visible without rebuild");
  await expect(page.getByRole("button", { name: "저장", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "글 관리", exact: true }).click();
  await page.getByLabel("글 검색").fill("브라우저 통합");
  await expect(page.locator("tbody tr")).toHaveCount(1);
  await page.getByLabel("채널 필터").selectOption("tech");
  await expect(page.locator("tbody tr")).toHaveCount(0);
  await page.getByLabel("채널 필터").selectOption("life");
  await page.getByRole("button", { name: "발행 취소", exact: true }).click();
  await expect(page.getByText("발행을 취소했습니다.")).toBeVisible();
  expect((await page.request.get(`${origin}/life/posts/dashboard-browser-check`)).status()).toBe(404);
  check("search, channel filter and unpublish");
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "휴지통으로", exact: true }).click();
  await expect(page.getByText("휴지통으로 이동했습니다.")).toBeVisible();
  await page.getByRole("navigation", { name: "관리자 메뉴" }).getByRole("button", { name: /휴지통/ }).click();
  await page.getByRole("button", { name: "복원", exact: true }).click();
  await expect(page.getByText("임시저장 상태로 복원했습니다.")).toBeVisible();
  await page.getByRole("button", { name: "글 관리", exact: true }).click();
  await expect(page.locator("tbody tr")).toHaveCount(1);
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "휴지통으로", exact: true }).click();
  await expect(page.getByText("휴지통으로 이동했습니다.")).toBeVisible();
  await page.getByRole("navigation", { name: "관리자 메뉴" }).getByRole("button", { name: /휴지통/ }).click();
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "영구 삭제", exact: true }).click();
  await expect(page.getByText("영구 삭제했습니다.")).toBeVisible();
  check("trash, restore as draft and permanent delete");
  expect((await page.request.post(`${origin}/admin/api/posts`, { data: {} })).status()).toBe(403);
  expect((await fetch(`${origin}/admin/api/posts`)).status).toBe(401);
  const oldCookies = await context.cookies();
  await page.getByRole("button", { name: "설정", exact: true }).click();
  await page.getByLabel("현재 비밀번호", { exact: true }).fill(password);
  await page.getByLabel("새 비밀번호", { exact: true }).fill(`${password}-new`);
  await page.getByLabel("새 비밀번호 확인", { exact: true }).fill(`${password}-new`);
  await page.getByRole("button", { name: "비밀번호 변경", exact: true }).click();
  await expect(page.getByRole("heading", { name: "관리자 로그인" })).toBeVisible();
  const staleContext = await browser.newContext();
  await staleContext.addCookies(oldCookies);
  expect((await staleContext.request.get(`${origin}/admin/api/posts`)).status()).toBe(401);
  await staleContext.close();
  await page.getByLabel("관리자 비밀번호", { exact: true }).fill(`${password}-new`);
  await page.getByRole("button", { name: "로그인", exact: true }).click();
  await expect(page.getByRole("heading", { name: "대시보드", exact: true })).toBeVisible();
  check("CSRF, unauthenticated access, password change and session revocation");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "관리자 메뉴 열기" }).click();
  await page.getByRole("button", { name: "글 관리", exact: true }).click();
  await expect(page.getByRole("heading", { name: "글 관리", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "/tmp/blog-admin-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "로그아웃", exact: true }).click();
  await expect(page.getByRole("heading", { name: "관리자 로그인" })).toBeVisible();
  expect((await context.cookies()).some((cookie) => cookie.name === "blog_admin_session")).toBe(false);
  await page.goto(`${origin}/life`);
  await expect(page.getByRole("banner")).toBeVisible();
  await expect(page.getByRole("contentinfo")).toBeVisible();
  expect(errors).toEqual([]);
  check("mobile navigation, logout cookie clearing, public layout and zero browser errors");
  writeFileSync("/tmp/blog-admin-verification.json", JSON.stringify({ results, passed: true }, null, 2));
} finally {
  await browser?.close();
  server.kill("SIGTERM");
  await new Promise((resolve) => { if (server.exitCode !== null) resolve(); else server.once("exit", resolve); });
  rmSync(directory, { recursive: true, force: true });
}
